serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const supabase = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
    );

    let reportOnly = false;
    let offset = 0;
    let batch = 6;
    try {
      const body = await req.json();
      reportOnly = Boolean(body?.report);
      if (Number.isFinite(Number(body?.offset))) offset = Math.max(0, Number(body.offset));
      if (Number.isFinite(Number(body?.batch))) batch = Math.min(Math.max(Number(body.batch), 1), 12);
    } catch (_e) { /* no body */ }


    if (reportOnly) {
      const { data } = await supabase.from("pet_faqs").select("category, embedding");
      const byCategory: Record<string, number> = {};
      let missingEmbeddings = 0;
      for (const row of data || []) {
        byCategory[row.category] = (byCategory[row.category] || 0) + 1;
        if (!row.embedding) missingEmbeddings++;
      }
      return new Response(
        JSON.stringify({ total: data?.length || 0, byCategory, missingEmbeddings, source_entries: FAQS.length }),
        { headers: { ...corsHeaders, "Content-Type": "application/json" } },
      );
    }

    // @ts-ignore - Supabase AI is available in the edge runtime
    const session = new Supabase.ai.Session("gte-small");

    let upserted = 0;
    let errors = 0;
    const slice = FAQS.slice(offset, offset + batch);

    for (const faq of slice) {
      try {
        const text = [faq.question, faq.subtopic, (faq.keywords || []).join(" "), faq.answer]
          .join(" ")
          .substring(0, 1000);
        // @ts-ignore
        const embedding = await session.run(text, { mean_pool: true, normalize: true });

        const row = {
          question: faq.question,
          answer: faq.answer,
          category: faq.category,
          subtopic: faq.subtopic,
          tags: faq.tags || [faq.category],
          keywords: faq.keywords || [],
          phone_numbers: faq.phones || [],
          is_active: true,
          embedding: JSON.stringify(Array.from(embedding)),
        };

        const { data: existing } = await supabase
          .from("pet_faqs")
          .select("id, version")
          .eq("question", faq.question)
          .maybeSingle();

        const { error } = existing
          ? await supabase
              .from("pet_faqs")
              .update({ ...row, version: (existing.version || 1) + 1 })
              .eq("id", existing.id)
          : await supabase.from("pet_faqs").insert(row);

        if (error) {
          console.error("FAQ upsert error:", faq.question, error);
          errors++;
        } else {
          upserted++;
        }
      } catch (e) {
        console.error("FAQ embedding error:", faq.question, e);
        errors++;
      }
    }

    const nextOffset = offset + slice.length;
    const done = nextOffset >= FAQS.length;

    if (done) {
      // Anything not in the source file is no longer official knowledge.
      const officialQuestions = new Set(FAQS.map((f) => f.question));
      const { data: allRows } = await supabase.from("pet_faqs").select("id, question");
      const staleIds = (allRows || []).filter((r: any) => !officialQuestions.has(r.question)).map((r: any) => r.id);
      if (staleIds.length > 0) {
        await supabase.from("pet_faqs").update({ is_active: false }).in("id", staleIds);
      }
    }

    return new Response(
      JSON.stringify({ upserted, errors, next_offset: done ? null : nextOffset, total_source: FAQS.length }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } },
    );

  } catch (error) {
    console.error("FAQ KB error:", error);
    return new Response(
      JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } },
    );
  }
});
